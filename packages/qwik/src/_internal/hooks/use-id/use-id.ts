import { useId as useQwikId, useConstant } from '@qwik.dev/core';

/**
 * An internal hook used to generate stable, unique identifiers with support for custom prefixes.
 *
 * It combines Qwik's `useId` for SSR-safe uniqueness with `useConstant` for client-side stability,
 * ensuring that the identifier remains unchanged throughout the component's entire lifecycle.
 *
 * This hook is designed for internal library use to provide consistent IDs for accessibility (A11Y)
 * and DOM manipulation across various design system component implementations.
 *
 * The generated identifier follows a specific structure:
 * `[prefix][autoId]`
 * - `prefix`: A trimmed string prepended to the ID (defaults to `"entry-ui-qwik-"`).
 * - `autoId`: A unique sequence automatically generated by Qwik's `useId` hook.
 *
 * Example Outputs:
 * - Default: `"entry-ui-qwik-rs7mG5255s"` (where `"entry-ui-qwik-"` is the `prefix`)
 * - Custom prefix: `"my-app-header-rs7mG5255s"` (where `"my-app-header-"` is the `prefix`)
 */
export const useId = (prefix: string | undefined = 'entry-ui-qwik-') => {
  // Retrieve an SSR-safe, automatically generated unique identifier string from Qwik's core primitives.
  // This value guarantees unique scope identity across both server and client rendering passes.
  const autoId = useQwikId();

  // Trim the `prefix`, concatenate it with the auto-generated ID, and freeze the result for the component lifecycle.
  // Uses `useConstant` to ensure the constructed ID string remains completely invariant across re-renders.
  const id = useConstant(() => `${prefix.trim()}${autoId}`);

  // Return the immutable, formatted identifier string.
  // Serves as the primary stable identifier for DOM elements and accessibility associations.
  return id;
};
