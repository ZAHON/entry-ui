import type { UseIdManagerParams, UseIdManagerReturnValue } from './use-id-manager.types';
import { useId as useQwikId, useSignal, $ } from '@qwik.dev/core';

/**
 * An internal hook used to manage unique identifiers with support for prefixes and manual state control.
 *
 * This hook provides a flexible way to handle DOM identifiers, ensuring accessibility
 * and consistency across components. It encapsulates the complexity of generating unique IDs
 * while offering granular control through dedicated `QRL` functions.
 *
 * This hook is designed for internal library use to streamline dynamic ID orchestration,
 * manage compound components' sub-element tracking, and abstract state lifecycle updates.
 *
 * The generated identifier follows a specific structure:
 * `[prefix][autoId]`
 * - `prefix`: A string prepended to the ID (defaults to `"entry-ui-qwik-"`).
 * - `autoId`: A unique sequence automatically generated by Qwik's `useId` hook.
 *
 * Example Outputs:
 * - Default: `"entry-ui-qwik-rs7mG5255s"` (where `"entry-ui-qwik-"` is the `prefix`)
 * - Custom prefix: `"my-app-header-rs7mG5255s"` (where `"my-app-header-"` is the `prefix`)
 */
export const useIdManager = (params: UseIdManagerParams = {}): UseIdManagerReturnValue => {
  const { prefix = 'entry-ui-qwik-', shouldInitialize = false } = params;

  // Retrieve an SSR-safe, automatically generated unique identifier string from Qwik's core primitives.
  // Guarantees stable unique scope identity across both server and client rendering passes.
  const autoId = useQwikId();

  // Initialize a reactive signal to hold the active string identifier state.
  // Conditionally pre-populates the trimmed `prefix` and `autoId` combination when `shouldInitialize` is enabled
  const id = useSignal<string | undefined>(shouldInitialize ? `${prefix.trim()}${autoId}` : undefined);

  const set$ = $((value: string | undefined) => {
    // Check if a valid, non-empty string override was provided to assign.
    // Assigns the custom value directly or falls back to the `prefix` and `autoId` combination.
    if (value && value.trim() !== '') {
      id.value = value;
    } else {
      id.value = `${prefix}${autoId}`;
    }
  });

  const delete$ = $(() => {
    // Reset the internal signal state to `undefined`.
    // Clears the active identifier reference for unmounting or deferred DOM targeting reset scenarios.
    id.value = undefined;
  });

  // Return the reactive readonly-wrapped signal reference and serialized mutation `QRL` handles.
  // Provides a complete identifier state management interface for consuming components.
  return { id, set$, delete$ };
};
